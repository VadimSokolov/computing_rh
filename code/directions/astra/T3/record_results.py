"""Flatten the independently generated result files into a numerical ledger."""

from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent


def flatten(value, path):
    if isinstance(value, dict):
        for key, item in value.items():
            yield from flatten(item, path + "." + key)
    elif isinstance(value, list):
        for i, item in enumerate(value):
            yield from flatten(item, path + "[" + str(i) + "]")
    else:
        yield path + " = " + str(value)


lines = ["Numerical ledger for report.md", "Generated by record_results.py", ""]
for name in ("core", "density", "zeros", "grid"):
    source = ROOT / "results" / (name + ".json")
    lines.extend(flatten(json.loads(source.read_text()), source.name))
    lines.append("")
(ROOT / "results" / "numbers.txt").write_text("\n".join(lines))
print("results/numbers.txt")
